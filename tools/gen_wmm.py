#!/usr/bin/env python3
"""Writes src/common/wmm_gen.cpp from the World Magnetic Model coefficients.

    tools/gen_wmm.py path/to/WMM.COF > src/common/wmm_gen.cpp

WMM.COF comes from NOAA: https://www.ncei.noaa.gov/products/world-magnetic-model
A new model is published every five years.
"""
import sys


def main():
    lines = open(sys.argv[1]).read().splitlines()
    epoch, name = lines[0].split()[:2]
    rows = []
    for line in lines[1:]:
        parts = line.split()
        if len(parts) != 6:
            break
        rows.append(parts)
    degree = max(int(r[0]) for r in rows)
    print("// SPDX-License-Identifier: GPL-3.0-only")
    print("// Generated by tools/gen_wmm.py from %s (NOAA/NCEI and BGS, public domain). Do not edit." % name)
    print('#include "common/wmm.h"')
    print()
    print("namespace mz {")
    print()
    print("const double kWmmEpoch = %s;" % epoch)
    print("const int kWmmDegree   = %d;" % degree)
    print("// degree, order, g, h (nT), and their change per year")
    print("const WmmRow kWmm[] = {")
    for n, m, g, h, dg, dh in rows:
        print("    {%s, %s, %s, %s, %s, %s}," % (n, m, g, h, dg, dh))
    print("};")
    print("const int kWmmRows = %d;" % len(rows))
    print()
    print("}  // namespace mz")


if __name__ == "__main__":
    main()
