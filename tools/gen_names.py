"""Generates src/ui/names_gen.cpp: printable names for protobuf enums.

Usage: tools/gen_names.py <protobufs checkout> > src/ui/names_gen.cpp
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1]) / "meshtastic"

ENUMS = [
    # (proto file, enum name, C++ function, fallback, prefix to strip)
    ("mesh.proto", "HardwareModel", "hw_model_name", "?", ""),
    ("portnums.proto", "PortNum", "portnum_name", "?", ""),
    ("mesh.proto", "Error", "routing_error_name", "?", ""),
    ("config.proto", "Role", "role_name", "?", ""),
]


def enum_values(path, name):
    text = re.sub(r"/\*.*?\*/", "", (root / path).read_text(), flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    match = re.search(r"enum\s+%s\s*\{(.*?)\}" % name, text, re.S)
    values = []
    for entry in re.finditer(r"(\w+)\s*=\s*(\d+)", match.group(1)):
        values.append((int(entry.group(2)), entry.group(1)))
    return values


print("// SPDX-License-Identifier: GPL-3.0-only")
print("// Generated by tools/gen_names.py from the protobuf definitions. Do not edit.")
print('#include "ui/mesh.h"')
print()
print("namespace mz {")
for path, enum, func, fallback, _ in ENUMS:
    print()
    print("const char* %s(int value)" % func)
    print("{")
    print("    switch (value) {")
    seen = set()
    for number, label in enum_values(path, enum):
        if number in seen:
            continue
        seen.add(number)
        label = label.replace("_APP", "") if enum == "PortNum" else label
        print('        case %d: return "%s";' % (number, label))
    print('        default: return "%s";' % fallback)
    print("    }")
    print("}")
print()
print("}  // namespace mz")
