"""Builds src/ui/fonts/embedded_fonts.c for the Cardputer ADV build.

The ADV has no file with the fonts on it, so Montserrat Medium and Bold are
cut down to the Latin letters and common signs, then stored in the program as
byte arrays. Needs fontTools (pip install fonttools).

    python3 tools/embed_fonts.py
"""
import io
import os

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "assets", "fonts")
OUT = os.path.join(ROOT, "src", "ui", "fonts", "embedded_fonts.c")

# Basic Latin, Latin-1, Latin Extended-A, Romanian commas, punctuation,
# euro, trademark, arrows, minus.
UNICODES = "U+0020-007E,U+00A0-017F,U+0218-021B,U+2010-2044,U+20AC,U+2122,U+2190-2199,U+2212"


def cut(name):
    opts = subset.Options()
    opts.layout_features = ["kern"]
    opts.hinting = False
    opts.desubroutinize = True
    opts.name_IDs = []
    opts.notdef_outline = True
    font = TTFont(os.path.join(FONTS, name))
    s = subset.Subsetter(opts)
    s.populate(unicodes=subset.parse_unicodes(UNICODES))
    s.subset(font)
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def c_array(var, data):
    lines = [f"const unsigned char {var}[{len(data)}] = {{"]
    for i in range(0, len(data), 20):
        lines.append("    " + ",".join(str(b) for b in data[i : i + 20]) + ",")
    lines.append("};")
    lines.append(f"const unsigned int {var}_len = {len(data)};")
    return "\n".join(lines)


def main():
    medium = cut("Montserrat-Medium.ttf")
    bold = cut("Montserrat-Bold.ttf")
    parts = [
        "/* Generated by tools/embed_fonts.py - do not edit. */",
        "/* Montserrat, SIL Open Font License 1.1 (assets/fonts/Montserrat-OFL.txt). */",
        "#if defined(MESHCARD_ESP32)",
        c_array("mz_montserrat_medium_ttf", medium),
        c_array("mz_montserrat_bold_ttf", bold),
        "#endif",
        "",
    ]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(parts))
    print(f"medium {len(medium)} bytes, bold {len(bold)} bytes -> {OUT}")


if __name__ == "__main__":
    main()
